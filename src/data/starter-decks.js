const starterDate = new Date('2026-09-10T00:00:00.000Z');

export function listStarterDecks() {
  return STARTER_DECKS.map(({ cards, ...deck }) => ({
    ...deck,
    ownerId: 'plananki',
    ownerNameSnapshot: 'ArteAnki',
    visibility: 'public',
    moderationStatus: 'approved',
    moderationNote: '',
    cardCount: cards.length,
    difficulty: DEFAULT_CARD_DIFFICULTY,
    createdAt: starterDate,
    updatedAt: starterDate,
    deletedAt: null,
  }));
}

export function getStarterDeck(id) {
  return listStarterDecks().find((deck) => deck.id === id) || null;
}

export function getStarterCards(deckId) {
  const deck = STARTER_DECKS.find((item) => item.id === deckId);
  return deck?.cards.map(([front, back], position) => ({
    id: `${deckId}-${String(position + 1).padStart(3, '0')}`,
    front,
    back,
    difficulty: DEFAULT_CARD_DIFFICULTY,
    position,
    createdAt: starterDate,
    updatedAt: starterDate,
  })) || null;
}
